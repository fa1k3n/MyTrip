// The service worker, written by the build with the list of the build's files (PW-03, PW-11), which also shows notices (NT-01, NT-04).
// Pure, so it runs under node --test.

/** The page, every built file and the home screen files; source maps are not needed (PW-01, PW-03). */
export const swFiles = (bundle: string[]) =>
  ["/", ...bundle.filter((f) => f !== "index.html" && !f.endsWith(".map")).map((f) => `/${f}`), "/manifest.webmanifest", "/icon-180.png", "/icon-192.png"];

/** A short name that changes with the file list, so every version gets its own cache and replaces the old one (PW-11). */
function version(files: string[]) {
  let h = 0;
  for (const c of files.join("\n")) h = (Math.imul(h, 31) + c.charCodeAt(0)) | 0;
  return (h >>> 0).toString(36);
}

/** The page comes from the network first, so a new version shows at the next start, and from the cache without a network,
 * or when the network is too slow. The hashed files come from the cache. The API is left to the app (PW-05, PW-17). */
export const swSource = (files: string[]) => `// Generated by sw-build.ts (PW-03, PW-11).
const CACHE = "mytrip-${version(files)}";
const FILES = ${JSON.stringify(files)};
self.addEventListener("install", (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener("activate", (e) => e.waitUntil(caches.keys()
  .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener("fetch", (e) => {
  const r = e.request, url = new URL(r.url);
  if (r.method !== "GET" || url.origin !== location.origin || url.pathname.startsWith("/api/")) return;
  if (r.mode === "navigate") {
    const net = fetch(r).then((res) => { if (res.ok) { const c = res.clone(); caches.open(CACHE).then((x) => x.put("/", c)); } return res; });
    const slow = new Promise((ok) => setTimeout(ok, 4000)).then(() => caches.match("/"));
    e.respondWith(Promise.race([net, slow.then((hit) => hit || net)]).catch(() => caches.match("/")));
    return;
  }
  e.respondWith(caches.match(r).then((hit) => hit || fetch(r)));
});
// NT-01: a notice from the server; NT-04: a tap opens the app on its trip.
self.addEventListener("push", (e) => {
  const n = e.data ? e.data.json() : {};
  e.waitUntil(self.registration.showNotification(n.title || "MyTrip", { body: n.body || "", data: { tripId: n.tripId }, icon: "/icon-192.png" }));
});
self.addEventListener("notificationclick", (e) => {
  e.notification.close();
  const url = "/?trip=" + encodeURIComponent((e.notification.data && e.notification.data.tripId) || "");
  e.waitUntil(self.clients.matchAll({ type: "window" }).then((open) => {
    const w = open.find((c) => "navigate" in c);
    return w ? w.navigate(url).then((c) => c && c.focus()) : self.clients.openWindow(url);
  }));
});
`;
